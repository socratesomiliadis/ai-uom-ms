const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{channel:'chrome'})});
  const page=await browser.newPage({viewport:{width:1600,height:958},deviceScaleFactor:1});
  const errors=[],network=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url());});
  const target=path.resolve('outputs/ai-production-lecture-el.html');
  const qa=path.resolve('build/deck-qa');fs.mkdirSync(qa,{recursive:true});
  await page.goto(pathToFileURL(target).href);
  await page.evaluate(async()=>{await Promise.all([...document.fonts].map(f=>f.load()));});
  const fontStatus=await page.evaluate(()=>[...document.fonts].map(f=>({family:f.family,weight:f.weight,style:f.style,status:f.status})));
  const geometry=[];
  const slideCount=await page.locator('.slide').count();
  if(slideCount!==28)throw Error('Unexpected slide count');
  for(let i=0;i<28;i++){
    await page.evaluate(n=>go(n),i);
    const footer=await page.locator('.slide:not([hidden]) .slide-footer').textContent();
    if(!footer.endsWith(`${String(i+1).padStart(2,'0')} / 28`))throw Error('Slide footer count mismatch');
    await page.screenshot({path:path.join(qa,`slide-${String(i+1).padStart(2,'0')}.png`),clip:{x:0,y:0,width:1600,height:900}});
    const issues=await page.locator('.slide:not([hidden])').evaluate(slide=>{
      const result=[];const content=slide.querySelector('.slide-content');
      const label=slide.querySelector('.label');
      const footer=slide.querySelector('.slide-footer').getBoundingClientRect();
      for(const el of content.querySelectorAll('h1,h2,h3,p,pre,blockquote,td,li,.clock-readout,.reveal-button')){
        if(el.hidden||el.closest('[hidden]'))continue;
        const r=el.getBoundingClientRect();
        if(r.right>1504||r.left<94||r.bottom>825||r.top<60)result.push({tag:el.tagName,text:el.textContent.slice(0,70),rect:{x:r.x,y:r.y,width:r.width,height:r.height}});
        if(el.scrollWidth>el.clientWidth+2&&getComputedStyle(el).display!=='inline'&&getComputedStyle(el).whiteSpace!=='normal')result.push({tag:el.tagName,text:el.textContent.slice(0,70),overflow:el.scrollWidth-el.clientWidth});
      }
      return result;
    });
    if(issues.length)geometry.push({slide:i+1,issues});
  }
  await page.evaluate(()=>go(0));
  await page.keyboard.press('ArrowRight');
  if(await page.locator('.slide:not([hidden])').getAttribute('data-index')!=='1')throw Error('Navigation failed');
  await page.keyboard.press('n');
  await page.locator('#notes-overlay').waitFor({state:'visible'});
  const notes=await page.locator('#notes-title').textContent();
  if(!notes.startsWith('2.'))throw Error('Notes mismatch');
  await page.keyboard.press('Escape');
  await page.keyboard.press('o');
  await page.locator('.overview-item').nth(4).click();
  if(await page.locator('.slide:not([hidden])').getAttribute('data-index')!=='4')throw Error('Overview navigation failed');
  await page.locator('#show-prices').click();
  if(await page.locator('.price-table.answers').count()!==1)throw Error('Reveal failed');
  await page.evaluate(()=>go(2));
  await page.locator('[data-reveal-target]').click();
  await page.locator('#contract-reveal').waitFor({state:'visible'});
  await page.evaluate(()=>go(9));
  await page.locator('[data-rounding="payable"]').click();
  if(!(await page.locator('#rounding-trace').textContent()).includes('45.05'))throw Error('Rounding switch failed');
  await page.locator('[data-rounding="discount"]').click();
  await page.evaluate(()=>go(7));
  await page.locator('.slide:not([hidden]) .start-clock').click();
  await page.waitForTimeout(1100);
  if(await page.locator('.slide:not([hidden]) .clock-readout').textContent()==='05:00')throw Error('Clock not running');
  await page.locator('.slide:not([hidden]) .reset-clock').click();
  if(await page.locator('.slide:not([hidden]) .clock-readout').textContent()!=='05:00')throw Error('Clock reset failed');
  await page.evaluate(()=>go(16));
  if(await page.locator('.slide:not([hidden]) .clock-readout').textContent()!=='03:00')throw Error('Peer review must be 3 minutes');
  await page.evaluate(()=>go(17));
  await page.keyboard.press('n');
  if(!(await page.locator('#notes-title').textContent()).startsWith('18.'))throw Error('Demo notes mismatch');
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>go(0));
  await page.screenshot({path:path.join(qa,'mobile.png')});
  const mobile=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth}));
  if(mobile.width>mobile.viewport)throw Error('Horizontal overflow on mobile');
  await page.setViewportSize({width:1600,height:958});
  await page.emulateMedia({media:'print'});
  const printed=await page.locator('.slide:visible').count();
  if(printed!==28)throw Error('Print misses slides');
  fs.writeFileSync(path.join(qa,'checks.json'),JSON.stringify({errors,network,fontStatus,geometry,printed,mobile},null,2));
  console.log(JSON.stringify({pageErrors:errors,networkRequests:network.length,fontStatus,geometry,printed,mobile},null,2));
  await browser.close();
  if(errors.length||geometry.length)process.exitCode=1;
})();
